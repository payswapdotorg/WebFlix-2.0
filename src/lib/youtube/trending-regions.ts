export const TRENDING_REGION_CODES = TRENDING_REGIONS.map((r) => r.code);

/**
 * Normalize any ?region= value into the map (invalid/unset → null = the
 * egress default — the read stays un-parameterized, exactly the pre-P23-C
 * behavior; an explicit valid region parameterizes both the SSR path and
 * the search fallback).
 */
export function normalizeTrendingRegion(
  value: string | null | undefined,
): string | null {
  if (!value) return null;
  const upper = value.toUpperCase();
  return TRENDING_REGION_CODES.includes(upper) ? upper : null;
}

/** The region's display name (the map's own — "??" never shown raw). */
export function trendingRegionName(code: string): string {
  return (
    TRENDING_REGIONS.find((r) => r.code === code.toUpperCase())?.name ??
    code.toUpperCase()
  );
}
