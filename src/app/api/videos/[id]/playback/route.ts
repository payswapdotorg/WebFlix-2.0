import { NextResponse } from "next/server";
import { getPlayback, pickProxyStreamFormat } from "@/lib/youtube/streams";
import {
  attemptChainStream,
  fetchUpstream,
  isAllowedStreamUrl,
  isUsable,
  streamOut,
} from "@/lib/youtube/stream-proxy";
import { rateLimit } from "@/lib/youtube/cache";

export const dynamic = "force-dynamic";
export const maxDuration = 60;

/**
 * Task 2-c — GET /api/videos/[id]/playback
 *
 * The embed-wall fallback chain's data source: server-side player response
 * (innertube `player` → the watch page's ytInitialPlayerResponse; see
 * src/lib/youtube/streams.ts). Returns `PlaybackDto` — `streamFormats` for
 * the native <video> swap and `storyboards` for the hover preview. Walled
 * egress → empty arrays (HTTP 200, the honest degrade the client renders
 * as the blocked card / zoom-pan).
 *
 * P31-HPV5 — THE BOX-PLAYER STREAM MODE: `?itag=<n>&stream=1`. The
 * operator's 2026-10-20 dispatch (verbatim: "all the long format video
 * boxes are showing slideshows instead they should be playing the video
 * from inside the box as if the box was a video player just like on
 * youtube.com"), on the measured production truth:
 *
 *  1. The EMBED lane is auth-walled from datacenter egresses on the
 *     healthy class now (both hosts — "Sign in to confirm you're not a
 *     bot", measured 2026-10-20; the wall MOVED since P28's matrix), and
 *     the operator reports the same from their side.
 *  2. The native lane's legacy fuel was architecturally dead in
 *     production: the client-held googlevideo URL is IP-bound to the
 *     PLAYBACK function's egress (this route!), and the legacy /api/stream
 *     function's own egress cannot run the playback chain at all (the P29
 *     regen's 11/11 fast-502s — 0.3s answers, no chain run possible).
 *  3. THIS function's egress demonstrably DOES win fresh playback chains
 *     (measured 2026-10-20: 4/4 never-cached obscure videos → itag-18
 *     formats via the watch-page rung; dQw4 → 22 formats via the player
 *     rung).
 *
 * So the stream bytes are served from THIS route's own invocation — the
 * one axis that always matches: a URL generated and fetched by the SAME
 * invocation. The flow:
 *
 *  - cache-first: getPlayback (the 10min L1/L2 chain cache — usually warm
 *    from the hover preview's card-mount prefetch, which hits this same
 *    route's DTO mode) → pickProxyStreamFormat (prefer the client's itag —
 *    a Range resume must ride the same stream; else the nearest-360p
 *    muxed-preferred law) → fetchUpstream (Range forwarded) → streamOut
 *    (the passthrough-header + anti-sniff CSP law);
 *  - dead URL (403 / unusable / throw) → ONE fresh retry:
 *    getPlayback(id, { fresh: true }) re-runs the whole chain in THIS
 *    invocation (the cache engine's force — the write-through makes the
 *    subsequent Range/seek requests ride the fresh URL instead of
 *    re-running the chain per request), then fetch again;
 *  - no usable format either attempt (the walled class) → the honest 502
 *    (the client's <video> fires onError → the lane falls to the embed
 *    fallback ladder → the honest floor; never a fake stream).
 *
 * The URLs fetched are ALWAYS our own chain's output — never client input
 * (no `url` parameter exists on this mode) — and every fetch still passes
 * the googlevideo allowlist (stream-proxy's law).
 */
export async function GET(req: Request, ctx: { params: Promise<{ id: string }> }) {
  if (!(await rateLimit(`playback:${req.headers.get("x-forwarded-for") ?? "local"}`))) {
    return NextResponse.json({ error: "Too many requests" }, { status: 429 });
  }
  let streamMode = false;
  try {
    const { id } = await ctx.params;
    if (!/^[A-Za-z0-9_-]{6,20}$/.test(id)) {
      return NextResponse.json({ error: "Invalid video id" }, { status: 400 });
    }
    const params = new URL(req.url).searchParams;
    streamMode = params.get("stream") === "1";
    if (!streamMode) {
      // The DTO law — byte-identical to the pre-P31 route.
      return NextResponse.json(await getPlayback(id));
    }

    // ---- P31-HPV5 — the box-player stream mode ----
    const itagRaw = params.get("itag");
    const preferItag =
      itagRaw !== null && /^\d{1,6}$/.test(itagRaw) ? Number.parseInt(itagRaw, 10) : null;
    const range = req.headers.get("range");

    // Attempt 1 — the cache-first chain answer (warm from the card-mount
    // prefetch in the common case). A cached URL was generated by a PAST
    // invocation of this function — egress rotation can leave it dead.
    const cached = await getPlayback(id);
    let upstream: Response | null = null;
    const cachedFmt = pickProxyStreamFormat(cached.streamFormats, preferItag);
    if (cachedFmt) {
      const url = isAllowedStreamUrl(cachedFmt.url);
      if (url) {
        try {
          const res = await fetchUpstream(url, range);
          if (isUsable(res)) upstream = res;
        } catch {
          /* dead or unreachable — the fresh retry below */
        }
      }
    }

    // Attempt 2 — the dead-URL cure: re-run the whole chain in THIS
    // invocation (force — no cache read, write-through) and fetch the
    // fresh URL it yields. Generate + fetch on one egress: the one axis
    // that always matches. P32-HPV6: attemptChainStream now rides the
    // MULTI-FORMAT TICKET LOOP (the fresh answer's picked format first —
    // the Range-resume law — then up to two more distinct-itag candidates
    // in the picker's own order; the moving wall is a per-format lottery).
    // Attempt 1 above stays the single cached pick: a cached generation's
    // URLs are dead TOGETHER.
    if (!upstream) {
      const fresh = await getPlayback(id, { fresh: true });
      upstream = await attemptChainStream(
        fresh.streamFormats,
        preferItag,
        range,
        pickProxyStreamFormat
      );
    }

    if (!upstream) {
      // The honest floor: the walled class (no formats anywhere) or a dead
      // upstream on both attempts. The client's <video> fires onError and
      // its lane falls to the embed fallback → the honest preview floor.
      return NextResponse.json({ error: "Playback stream unavailable" }, { status: 502 });
    }
    return streamOut(upstream);
  } catch (err) {
    console.error("GET /api/videos/[id]/playback failed", err);
    if (streamMode) {
      // The stream mode's honest floor — the client's <video> fires
      // onError and its lane falls to the embed fallback ladder.
      return NextResponse.json({ error: "Playback stream failed" }, { status: 502 });
    }
    return NextResponse.json(
      { streamFormats: [], storyboards: [], durationSec: null, source: "" },
      { status: 200 }
    );
  }
}
