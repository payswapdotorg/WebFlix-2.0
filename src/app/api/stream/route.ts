import { NextResponse } from "next/server";
import { getPlayback } from "@/lib/youtube/streams";
import type { StreamFormatDto } from "@/lib/watch/types";

export const dynamic = "force-dynamic";
export const maxDuration = 60;

/**
 * Task 2-c — GET /api/stream?url=<encoded googlevideo URL>
 *
 * The local proxy for the embed-wall fallback's native <video> swap.
 * googlevideo.com videoplayback URLs are IP-bound (they only play from the
 * egress that fetched them — the server), so the browser can never fetch
 * them directly. This route streams them same-origin:
 *  - ALLOWLIST: https + *.googlevideo.com only (never a generic proxy);
 *  - `Range` request header is forwarded (seek support) and the upstream
 *    206/200 + content-type/-length/-range + accept-ranges are passed
 *    through verbatim;
 *  - redirects followed (the CDN bounces between hosts);
 *  - 60s budget — enough to start + serve a progressive segment; the
 *    player retries its own Range requests as needed.
 *
 * P29-STREAM-REGEN — the SELF-HEALING pass. On a serverless deploy
 * (production), the playback API and this proxy run as SEPARATE functions
 * whose egress IPs differ, so a client-held `url` (generated by the
 * playback function's egress) answers 403 from THIS function's egress —
 * measured live 2026-10-20 on production: 5/5 probes dead with
 * "Upstream stream responded 403" while the very same URL played fine
 * from the single-egress dev server. The cure rides the one axis that
 * always matches: a URL generated and fetched by the SAME invocation.
 * Clients append `&video=<id>` and `&itag=<n>` (the format they picked):
 * on a 403 the route re-runs the server-side playback chain
 * (`getPlayback` — THIS function's egress), prefers the SAME itag when the
 * fresh answer carries it (a Range resume must ride the same stream; else
 * the nearest-360p law, the server twin of the client picker) and streams
 * THAT. A per-instance regen cache (videoId → fresh URL, 10min TTL,
 * invalidated by its own 403) keeps seek/Range storms from re-running the
 * chain per request. The regen fetches only URLs from our own getPlayback
 * output — never client input — and still passes them through the same
 * allowlist. No `video` param: the old behavior (an honest 502).
 */
const ALLOWED_HOST_SUFFIX = ".googlevideo.com";

function isAllowedStreamUrl(raw: string): URL | null {
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    return null;
  }
  if (url.protocol !== "https:") return null;
  const host = url.hostname.toLowerCase();
  if (!host.endsWith(ALLOWED_HOST_SUFFIX) && host !== "googlevideo.com") return null;
  return url;
}

const PASSTHROUGH_HEADERS = [
  "content-type",
  "content-length",
  "content-range",
  "accept-ranges",
  "cache-control",
] as const;

/* ------------------------------------------------------------------ */
/* P29-STREAM-REGEN — the regen machinery                              */
/* ------------------------------------------------------------------ */

/** YouTube video ids: 11 chars in the wild; the window is honest paranoia. */
const VIDEO_ID_RE = /^[A-Za-z0-9_-]{6,20}$/;

/** Mirrors the playback chain's own WATCH_MS — one regen per warm window. */
const REGEN_TTL_MS = 10 * 60 * 1000;

/**
 * Per-instance regen cache: videoId → the fresh URL this lambda last
 * regenerated (bound to THIS egress). A seek/Range storm rides the cached
 * URL without re-running the playback chain; a dead cached URL (403)
 * invalidates itself and the next request re-heals.
 */
const regenCache = new Map<string, { url: string; itag: number; at: number }>();

/** Test seam (the setUpstream/clearCache convention) — resets the regen cache. */
export function resetProxyRegenCache(): void {
  regenCache.clear();
}

/**
 * The server twin of the client's pickPreviewStreamFormat
 * (src/lib/watch/playback-client.ts): prefer the EXACT itag the client
 * picked (a Range resume must ride the same stream), else the
 * nearest-360p law — muxed (hasAudio) entries preferred so a watch-page
 * fallback never lands on a silent stream, any entry as the last resort.
 */
function pickProxyStreamFormat(
  formats: StreamFormatDto[],
  preferItag: number | null
): StreamFormatDto | null {
  if (formats.length === 0) return null;
  if (preferItag !== null) {
    const exact = formats.find((f) => f.itag === preferItag);
    if (exact) return exact;
  }
  const score = (f: StreamFormatDto): number =>
    -Math.abs((f.height ?? 0) - 360) * 1000 + (f.hasAudio ? 500 : 0) - (f.bitrate ?? 0) / 1e9;
  const withAudio = formats.filter((f) => f.hasAudio);
  const pool = withAudio.length > 0 ? withAudio : formats;
  return pool.reduce((best, f) => (score(f) > score(best) ? f : best));
}

/** One upstream attempt — the plain-fetch law googlevideo expects. */
async function fetchUpstream(upstreamUrl: URL, range: string | null): Promise<Response> {
  return fetch(upstreamUrl, {
    redirect: "follow",
    headers: {
      // googlevideo requires noReferer-ish plain fetches; a Range when present
      ...(range ? { Range: range } : {}),
      Accept: "*/*",
    },
    signal: AbortSignal.timeout(60_000),
    cache: "no-store",
  });
}

function isUsable(upstream: Response): boolean {
  return upstream.ok || upstream.status === 206;
}

function streamOut(upstream: Response): Response {
  const headers = new Headers();
  for (const name of PASSTHROUGH_HEADERS) {
    const value = upstream.headers.get(name);
    if (value !== null) headers.set(name, value);
  }
  // a same-origin proxy must never let the browser sniff something else
  headers.set("content-security-policy", "default-src 'none'; media-src 'self'");
  headers.set("x-content-type-options", "nosniff");
  return new Response(upstream.body, { status: upstream.status, headers });
}

/**
 * The heal: try the cached fresh URL first (the Range-storm fast path),
 * then re-run the playback chain from THIS invocation's egress and fetch
 * the fresh URL it yields. Null = the heal failed honestly (walled chain
 * or the fresh URL died too) — the caller degrades to the 502 floor.
 */
async function healWithRegen(
  videoId: string,
  preferItag: number | null,
  range: string | null
): Promise<Response | null> {
  const cached = regenCache.get(videoId);
  if (cached && Date.now() - cached.at < REGEN_TTL_MS) {
    const cachedUrl = isAllowedStreamUrl(cached.url);
    if (cachedUrl) {
      try {
        const res = await fetchUpstream(cachedUrl, range);
        if (isUsable(res)) return res;
        if (res.status === 403) regenCache.delete(videoId); // dead again — re-heal below
      } catch {
        regenCache.delete(videoId); // transient — the regen below retries
      }
    } else {
      regenCache.delete(videoId);
    }
  }

  const playback = await getPlayback(videoId);
  const fmt = pickProxyStreamFormat(playback.streamFormats, preferItag);
  if (!fmt) return null; // the walled class — no honest stream to serve
  const freshUrl = isAllowedStreamUrl(fmt.url);
  if (!freshUrl) return null; // structurally impossible (our own chain) — belt and braces
  try {
    const res = await fetchUpstream(freshUrl, range);
    if (isUsable(res)) {
      regenCache.set(videoId, { url: fmt.url, itag: fmt.itag, at: Date.now() });
      return res;
    }
  } catch {
    /* honest fall-through */
  }
  return null;
}

export async function GET(req: Request) {
  const params = new URL(req.url).searchParams;
  const target = params.get("url");
  if (!target) {
    return NextResponse.json({ error: "Missing url parameter" }, { status: 400 });
  }
  const upstreamUrl = isAllowedStreamUrl(target);
  if (!upstreamUrl) {
    return NextResponse.json(
      { error: "Only googlevideo.com stream URLs can be proxied" },
      { status: 400 }
    );
  }

  const range = req.headers.get("range");
  // P29 — the self-healing pair: the client's video id (whose playback
  // chain this route can re-run) and the itag it picked (Range resumes
  // must ride the same stream). Absent/invalid → the old url-only law.
  const videoParam = params.get("video");
  const videoId = videoParam !== null && VIDEO_ID_RE.test(videoParam) ? videoParam : null;
  const itagParam = params.get("itag");
  const preferItag =
    itagParam !== null && /^\d{1,6}$/.test(itagParam) ? Number.parseInt(itagParam, 10) : null;

  let upstream: Response;
  try {
    upstream = await fetchUpstream(upstreamUrl, range);
  } catch (err) {
    const aborted = err instanceof Error && err.name === "TimeoutError";
    return NextResponse.json(
      { error: aborted ? "Upstream stream timed out" : "Upstream stream failed" },
      { status: aborted ? 504 : 502 }
    );
  }

  // P29 — the IP-bound signature: the client-held URL was generated by a
  // DIFFERENT function's egress. Heal from this invocation's own chain.
  if (upstream.status === 403 && videoId !== null) {
    const healed = await healWithRegen(videoId, preferItag, range);
    if (healed) return streamOut(healed);
    return NextResponse.json(
      { error: "Upstream stream responded 403 (regen unavailable)" },
      { status: 502 }
    );
  }

  if (!isUsable(upstream)) {
    return NextResponse.json(
      { error: `Upstream stream responded ${upstream.status}` },
      { status: 502 }
    );
  }

  return streamOut(upstream);
}
